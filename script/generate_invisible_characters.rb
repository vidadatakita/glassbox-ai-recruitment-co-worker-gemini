# frozen_string_literal: true

# Generates app/models/invisible_characters.rb: every code point that is Unicode White_Space, a format
# character (Cf) or a Default_Ignorable_Code_Point, as ranges. ONE source for the Ruby check
# (Progression.blank_note?) and the database function note_present() (migration 20261010235800 builds
# it from this constant; test/models/invisible_characters_test.rb compares the two on every code point).
# Engine 11 F-14/F-15: a hand-written list kept missing characters (em space, braille blank, hangul
# fillers, CGJ, soft hyphen, LRM/RLM, U+180E). Run with the project's Ruby; the Unicode version is the
# one that Ruby ships and is printed in the generated file.
#
#   ruby script/generate_invisible_characters.rb
PATTERN = /[\p{White_Space}\p{Cf}\p{Default_Ignorable_Code_Point}]/
# U+2800 BRAILLE PATTERN BLANK, U+115F/U+1160/U+3164/U+FFA0 HANGUL FILLERs render as blank but are
# letters/symbols in Unicode; named by engine 11 (F-15) and added on purpose.
EXTRA = [0x2800, 0x115F, 0x1160, 0x3164, 0xFFA0].freeze

points = (0..0x10FFFF).reject { |cp| cp.between?(0xD800, 0xDFFF) }.select { |cp| [cp].pack("U").match?(PATTERN) }
points = (points + EXTRA).uniq.sort
ranges = points.slice_when { |a, b| b != a + 1 }.map { |run| [run.first, run.last] }
body = ranges.map { |(a, b)| format("    [0x%04X, 0x%04X]", a, b) }.join(",\n")

header = "# GENERATED by script/generate_invisible_characters.rb (Ruby #{RUBY_VERSION}, " \
         "Unicode #{RbConfig::CONFIG['UNICODE_VERSION']}). #{points.size} code points.\n"
static = <<~'TEXT'
  # Do not edit by hand: change the generator and run it, then add a migration that rebuilds
  # note_present() from this constant (the database must hold the same list; a test compares them).
  #
  # Every code point that is Unicode White_Space, a format character (Cf) or a default-ignorable code
  # point, plus the blank-looking fillers named in the generator: a note made only of these is EMPTY
  # (engine 11 F-04, F-14, F-15).
  module InvisibleCharacters
    RANGES = [
TEXT
tail = <<~'TEXT'
    ].freeze

    CLASS = Regexp.new("[" + RANGES.map { |(a, b)| a == b ? format("\\u{%X}", a) : format("\\u{%X}-\\u{%X}", a, b) }.join + "]")

    def self.code_points = RANGES.flat_map { |(a, b)| (a..b).to_a }
  end
TEXT
File.write(File.expand_path("../app/models/invisible_characters.rb", __dir__), header + static + body + "\n" + tail)
puts "#{points.size} code points in #{ranges.size} ranges"
